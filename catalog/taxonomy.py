# Matched against product_type (weight 3), title (2) and tags (0.5). A title
# hit alone is enough to link a product; a tag hit alone is not.
LINK_THRESHOLD = 2.0
MAX_SUBS = 3

def _phrase(p):
    """Whole-word for one word (plural allowed), phrase-with-word-edges for more."""
    parts = [re.escape(w) for w in p.split()]
    body = r"[\s\-]+".join(parts)
    return r"\b" + body + r"(?:s|es)?\b"


_compiled = {
    cat: [(sub, name, [re.compile(_phrase(p), re.I) for p in phrases])
          for sub, name, phrases in subs]
    for cat, subs in SUBCATEGORIES.items()
}



def subcategories_of(product, category):
    """Every aisle in `category` this product belongs to, strongest first."""
    subs = _compiled.get(category)
    if not subs:
        return []
    tags = product.get("tags") or []
    fields = [((product.get("product_type") or ""), 3.0),
              ((product.get("title") or ""), 2.0),
              ((" ".join(tags) if isinstance(tags, list) else tags or ""), 0.5)]
    scored = []
    for sub, _name, pats in subs:
        score = 0.0
        for text, weight in fields:
            if text and any(p.search(text) for p in pats):
                score += weight
        if score >= LINK_THRESHOLD:
            scored.append((score, sub))
    scored.sort(key=lambda s: (-s[0], s[1]))
    return [sub for _score, sub in scored[:MAX_SUBS]]


# Aisles added on top of a brand's saved aisle list (brands.json
# product_subcategories), which otherwise wins: they arrived after most lists
# were saved, and a saved "pants" product can still be a sweatpant.
ADDED_AISLES = {"clothing": ["sweatpants"]}


def with_added_aisles(product, category, subs):
    """`subs` plus every ADDED_AISLES aisle the product's title or type names."""
    out = list(subs or [])
    pats = {sub: ps for sub, _name, ps in _compiled.get(category, [])}
    text = f"{product.get('product_type') or ''} {product.get('title') or ''}"
    for sub in ADDED_AISLES.get(category, []):
        if sub not in out and any(p.search(text) for p in pats.get(sub, [])):
            out.append(sub)
    return out


def flat_subcategories():
    """[{id, name, category}] in taxonomy order, ids namespaced by category."""
    return [{"id": f"{cat}:{sub}", "name": name, "category": cat}
            for cat, subs in SUBCATEGORIES.items()
            for sub, name, _phrases in subs]
